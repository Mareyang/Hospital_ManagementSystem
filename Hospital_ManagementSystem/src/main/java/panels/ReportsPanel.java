    private Object[][] fetchReports(String queryTerm) {
        List<Object[]> rowsList = new ArrayList<>();
        String sql = "SELECT r.report_id, r.report_title, t.type_name as report_type, u.firstname, u.lastname, r.generated_datetime " +
                     "FROM hospital_reports r " +
                     "LEFT JOIN report_types t ON r.report_type_id = t.type_id " +
                     "LEFT JOIN users u ON r.generated_by_id = u.user_id";
        
        boolean hasSearchFilter = !queryTerm.isEmpty() && !queryTerm.equals("Search by report name or type...");
        
        if (hasSearchFilter) {
            sql += " WHERE r.report_title LIKE ? OR t.type_name LIKE ? OR r.report_id LIKE ?";
        }
        sql += " ORDER BY r.report_id DESC"; 

        // Variables to hold dynamic dashboard counts
        int countTotal = 0;
        int countClinical = 0;
        int countPatient = 0;
        int countAdmin = 0;

        try (Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/hospital_management", "root", "");
             PreparedStatement statement = conn.prepareStatement(sql)) {
            
            if (hasSearchFilter) {
                String cleanSearch = queryTerm.replace("RPT-", "").replace("rpt-", "");
                statement.setString(1, "%" + queryTerm + "%");
                statement.setString(2, "%" + queryTerm + "%");
                statement.setString(3, "%" + cleanSearch + "%");
            }

            ResultSet result = statement.executeQuery();
            while (result.next()) {
                int rawId = result.getInt("report_id");
                String reportID = String.format("RPT-%03d", rawId);
                String reportName = result.getString("report_title");
                String type = result.getString("report_type");
                String firstName = result.getString("firstname");
                String lastName = result.getString("lastname");
                String generatedBy = (firstName != null && lastName != null) ? firstName + " " + lastName : "System";
                String dateGenerated = result.getString("generated_datetime");
                String status = "Generated"; // Static status since it's generated

                countTotal++;
                // Dynamic metric classification grouping
                if (type != null) {
                    if (type.contains("Clinical") || type.contains("Medical") || type.contains("Inventory")) countClinical++;
                    else if (type.contains("Patient") || type.contains("Appointment")) countPatient++;
                    else if (type.contains("Staff") || type.contains("Financial") || type.contains("HR") || type.contains("Billing")) countAdmin++;
                }

                rowsList.add(new Object[]{reportID, reportName, type, generatedBy, dateGenerated, status});
            }
            
        } catch (SQLException ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Failed to load reports from database.", "Database Error", JOptionPane.ERROR_MESSAGE);
        }

        refreshSummaryCards(countTotal, countClinical, countPatient, countAdmin);

        return rowsList.toArray(new Object[0][]);
    }

